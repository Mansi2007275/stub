import { readFileSync, writeFileSync } from "node:fs";
const art = /** @type {{ abi: unknown[] }} */ (JSON.parse(readFileSync("out/StubEscrow.sol/StubEscrow.json", "utf8")));
const src = `// AUTO-GENERATED by scripts/export-abi.mjs — do not edit by hand.\nexport const escrowAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
writeFileSync("src/lib/escrowAbi.ts", src);
writeFileSync("lib/server/escrowAbi.ts", src);
writeFileSync("shared/escrowAbi.ts", src);
console.log(`exported ${art.abi.length} ABI entries`);
